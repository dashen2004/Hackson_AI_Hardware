#define ERR_INPROGRESS (-5)    /* Operation in progress    */
#define ERR_VAL        (-6)    /* Illegal value.           */
#define ERR_DB         (-7)    /* db error.                */
#define ERR_FILE       (-8)    /* file error.              */



#endif
